function resolveMessage(tree: MessageTree, key: string): string | undefined {
  return key.split(".").reduce<string | MessageTree | undefined>((current, part) => {
    if (!current || typeof current === "string") {
      return current;
    }

    return current[part];
  }, tree) as string | undefined;
}

function interpolate(template: string, values?: TranslationValues) {
  if (!values) {
    return template;
  }

  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

type TranslationContextValue = {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: TranslationValues) => string;
};

const TranslationContext = React.createContext<TranslationContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = React.useState<Language>("en");

  React.useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY);

    if (saved === "en" || saved === "bg") {
      setLanguage(saved);
      return;
    }

    if (window.navigator.language.toLowerCase().startsWith("bg")) {
      setLanguage("bg");
    }
  }, []);

  React.useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language === "bg" ? "bg" : "en";
  }, [language]);

  const value = React.useMemo<TranslationContextValue>(
    () => ({
      language,
      locale: localeByLanguage[language],
      setLanguage,
      t: (key, values) => {
        const languageMessage = resolveMessage(messages[language], key);
        const fallbackMessage = resolveMessage(messages.en, key);
        return interpolate(languageMessage ?? fallbackMessage ?? key, values);
      },
    }),
    [language],
  );

  return <TranslationContext.Provider value={value}>{children}</TranslationContext.Provider>;
}

export function useTranslations() {
  const context = React.useContext(TranslationContext);

  if (!context) {
    throw new Error("useTranslations must be used inside LanguageProvider.");
  }

  return context;
}

export function getRoleLabel(
  role: string | null | undefined,
  translate: (key: string, values?: TranslationValues) => string,
) {
  if (role === "ADMIN") {
    return translate("roles.admin");
  }

  if (role === "LEADER") {
    return translate("roles.leader");
  }

  if (role === "EMPLOYEE") {
    return translate("roles.employee");
  }

  return translate("roles.unknown");
}
